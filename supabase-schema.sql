create table public.countdown_updates (
  id bigint generated by default as identity primary key,
  text text not null check (char_length(trim(text)) between 1 and 160),
  person text check (person in ('boyfriend', 'girlfriend')),
  channel text not null,
  update_date date not null,
  created_at timestamptz not null default now()
);

alter table public.countdown_updates enable row level security;

create policy "Anyone can view countdown updates"
on public.countdown_updates
for select
to anon
using (true);

create policy "Anyone can add countdown updates"
on public.countdown_updates
for insert
to anon
with check (true);

create policy "Anyone can delete countdown updates"
on public.countdown_updates
for delete
to anon
using (true);

alter publication supabase_realtime add table public.countdown_updates;
